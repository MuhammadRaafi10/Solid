BASE=os.environ.get('BASE','http://localhost/solid/api/index.php?action=')
class C:
    def __init__(s):
        s.cj=http.cookiejar.CookieJar(); s.op=urllib.request.build_opener(urllib.request.HTTPCookieProcessor(s.cj))
    def call(s, a, p=None, expect_ok=True):
        req=urllib.request.Request(BASE+a, data=json.dumps(p or {}).encode(), headers={'Content-Type':'application/json','X-Requested-With':'solid'})
        try: r=s.op.open(req); body=r.read()
        except urllib.error.HTTPError as e: body=e.read()
        j=json.loads(body)
        if expect_ok and not j['ok']: raise Exception(a+' -> '+str(j))
        if not expect_ok and j['ok']: raise Exception(a+' unexpectedly ok')
        return j['data'] if j['ok'] else j
